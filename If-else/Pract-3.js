// Positive, Negative, or Zero: Write a program to input a number and check if it's positive, negative, or zero using if-else statements.

let num = -5;

if (num > 0) 
{
    console.log("Number is Positive");
} 
else if (num < 0) 
{
    console.log("Number is Negative");
} 
else 
{
    console.log("Number is Zero");
}