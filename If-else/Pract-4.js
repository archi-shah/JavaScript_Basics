// Grading System: Create a program that takes a student's score as input and assigns a grade (A, B, C, D, or F)
//  based on predefined criteria using if-else statements.

let marks = 75;

if (marks >= 90) 
{
    console.log("Grade: A");
}
else if (marks >= 80) 
{
    console.log("Grade: B");
}
else if (marks >= 70) 
{
    console.log("Grade: C");
}
else if (marks >= 60) 
{
    console.log("Grade: D");
}
else 
{
    console.log("Grade: F");
}